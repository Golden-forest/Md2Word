// Generates lib/katexCssString.ts from the installed katex package's stylesheet.
//
// WHY: The HTML export feature inlines KaTeX's CSS into the exported .html so
// the single file renders math without an external <link>. KaTeX's CSS
// references its fonts via RELATIVE urls (url(fonts/KaTeX_AMS-Regular.woff2)).
// A standalone .html opened anywhere has no fonts/ sibling, so we rewrite those
// urls to a public CDN absolute path. The result is committed to the repo as a
// deterministic string constant — re-run this only when you bump katex.
//
// Run (after a katex version bump):  node scripts/gen-katex-css-string.mjs

import { readFile, writeFile } from "node:fs/promises";

const KATEX_CSS_PATH = "node_modules/katex/dist/katex.min.css";
const KATEX_VERSION = "0.16.47"; // keep in sync with package.json
const OUT_PATH = "lib/katexCssString.ts";
const CDN_BASE = `https://cdn.jsdelivr.net/npm/katex@${KATEX_VERSION}/dist/`;

const css = await readFile(KATEX_CSS_PATH, "utf8");

// Rewrite relative font urls (url(fonts/...) and url("./fonts/...")) to the CDN.
// KaTeX ships only `url(fonts/...)` forms, but be defensive about quoting.
const rewritten = css.replace(
  /url\((['"]?)(\.\/)?fonts\//g,
  (_, quote, _prefix) => `url(${quote}${CDN_BASE}fonts/`,
);

// Escape for a JS double-quoted string literal: backslash, quotes, newlines.
const escaped = rewritten.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n");

const output = `// AUTO-GENERATED by scripts/gen-katex-css-string.mjs — DO NOT EDIT BY HAND.
// KaTeX ${KATEX_VERSION} stylesheet with font urls rewritten to a public CDN so the
// CSS can be inlined into a standalone exported .html and still load its fonts.
// Regenerate after bumping katex:  node scripts/gen-katex-css-string.mjs
export const KATEX_CSS_STRING = "${escaped}";
`;

await writeFile(OUT_PATH, output, "utf8");

const fontUrls = rewritten.match(/url\([^)]+KaTeX_[^)]+\)/g) ?? [];
console.log(`Wrote ${OUT_PATH} (${rewritten.length} chars of CSS, ${fontUrls.length} font urls rewritten to ${CDN_BASE}fonts/…)`);
